// Cleans public.documents (Step 1 of docs/rag-improvement-plan.md).
//
//   npm run clean-docs                    → dry run: backs up the table, writes the plan, changes NOTHING
//   npm run clean-docs -- --yes           → backs up again, then applies the plan
//   npm run clean-docs -- --restore <f>   → re-inserts every row from a backup whose id no longer exists
//
// The plan:
//   1. Exact duplicates: keep the oldest copy, delete the rest.
//   2. Oversized rows (> MAX_ROW_CHARS): split with the app's chunker, insert the pieces that don't
//      exist yet, delete the original. (These are early uploads of pages that were later re-chunked.)
//   3. Boilerplate-only rows (page headers, legal disclaimer, survey footer): delete.
// The vet directory (SENASICA's MVRA list) is only counted: it belongs in its own table (Step 1.4).
//
// Backups go to backups/ (git-ignored): id, content, embedding and created_at of every row.
import fs from "node:fs";
import path from "node:path";
import { createClient } from "@supabase/supabase-js";
import { ensureSupabaseConfigured } from "../lib/supabase.ts";
import { generateEmbedding } from "../lib/embeddings.ts";
import { splitTextIntoChunks, usefulText } from "../lib/chunking.ts";

type Row = { id: string; content: string; embedding: unknown; created_at: string };

const MAX_ROW_CHARS = 1200;
const MIN_USEFUL_CHARS = 80;
const BACKUP_DIR = path.resolve(import.meta.dirname, "../backups");

const args = process.argv.slice(2);
const apply = args.includes("--yes");
const restoreIndex = args.indexOf("--restore");

/**
 * The live database does not let the anon key delete rows (row-level security), so deletes need
 * SUPABASE_SERVICE_ROLE_KEY. Without it, --yes stops and points to the SQL alternative.
 */
function adminClient() {
  const url = (process.env.VITE_SUPABASE_URL ?? "").trim();
  const serviceKey = (process.env.SUPABASE_SERVICE_ROLE_KEY ?? "").trim();
  return url && serviceKey ? createClient(url, serviceKey, { auth: { persistSession: false } }) : null;
}

/** Same plan as SQL, for the Supabase SQL editor. Aborts unless exactly the planned rows are deleted. */
function planToSql(ids: string[]): string {
  return [
    "-- Generated by scripts/cleanDocuments.ts. Paste into Supabase → SQL Editor → Run.",
    "-- Deletes exactly the rows listed in the plan, or nothing at all.",
    "begin;",
    "do $$",
    "declare deleted int;",
    "begin",
    "  delete from public.documents where id in (",
    ids.map((id) => `    '${id}'`).join(",\n"),
    "  );",
    "  get diagnostics deleted = row_count;",
    `  if deleted <> ${ids.length} then`,
    `    raise exception 'Expected to delete ${ids.length} rows, got %. Nothing was changed.', deleted;`,
    "  end if;",
    "end $$;",
    "",
    "-- schema.sql step 6: from now on, duplicate chunks are rejected.",
    "alter table public.documents add column if not exists content_hash text generated always as (md5(content)) stored;",
    "create unique index if not exists documents_content_hash_key on public.documents (content_hash);",
    "commit;",
    "",
  ].join("\n");
}

function isDirectory(content: string): boolean {
  return (content.match(/@[a-z0-9.-]+\.\s?(com|mx)/gi) ?? []).length >= 2;
}

function preview(content: string, length = 110): string {
  return content.replace(/\s+/g, " ").slice(0, length);
}

async function fetchAll(): Promise<Row[]> {
  const supabase = ensureSupabaseConfigured();
  const rows: Row[] = [];
  for (let from = 0; ; from += 500) {
    const { data, error } = await supabase
      .from("documents")
      .select("id, content, embedding, created_at")
      .order("created_at")
      .order("id")
      .range(from, from + 499);
    if (error) throw error;
    rows.push(...((data ?? []) as Row[]));
    if (!data || data.length < 500) break;
  }
  return rows;
}

function backup(rows: Row[]): string {
  fs.mkdirSync(BACKUP_DIR, { recursive: true });
  const file = path.join(BACKUP_DIR, `documents-${new Date().toISOString().replace(/[:.]/g, "-")}.json`);
  fs.writeFileSync(file, JSON.stringify(rows));
  return file;
}

async function restore(file: string) {
  const supabase = ensureSupabaseConfigured();
  const rows = JSON.parse(fs.readFileSync(file, "utf8")) as Row[];
  const existing = new Set((await fetchAll()).map((row) => row.id));
  const missing = rows.filter((row) => !existing.has(row.id));
  console.log(`Backup: ${rows.length} filas · faltan en la base: ${missing.length}`);
  for (let i = 0; i < missing.length; i += 100) {
    const { error } = await supabase.from("documents").insert(missing.slice(i, i + 100));
    if (error) throw error;
  }
  console.log(`✅ ${missing.length} filas restauradas.`);
}

async function main() {
  if (restoreIndex >= 0) return restore(args[restoreIndex + 1]);

  const supabase = ensureSupabaseConfigured();
  const rows = await fetchAll();
  const backupFile = backup(rows);
  console.log(`Respaldo: ${rows.length} filas → ${path.relative(process.cwd(), backupFile)}\n`);

  // 1. Exact duplicates (rows are ordered oldest first, so the first copy is kept).
  const keptByContent = new Map<string, Row>();
  const duplicates: Row[] = [];
  for (const row of rows) {
    if (keptByContent.has(row.content)) duplicates.push(row);
    else keptByContent.set(row.content, row);
  }
  const unique = [...keptByContent.values()];

  // 2. Oversized rows: re-chunk, keep only pieces that are new.
  const oversized = unique.filter((row) => row.content.length > MAX_ROW_CHARS);
  const existingContent = new Set(unique.filter((row) => !oversized.includes(row)).map((row) => row.content));
  const newChunks = new Set<string>();
  for (const row of oversized) {
    for (const chunk of splitTextIntoChunks(row.content)) {
      if (!existingContent.has(chunk) && usefulText(chunk).length >= MIN_USEFUL_CHARS) newChunks.add(chunk);
    }
  }

  // 3. Boilerplate-only rows.
  const boilerplate = unique.filter((row) => !oversized.includes(row) && usefulText(row.content).length < MIN_USEFUL_CHARS);

  const directory = unique.filter((row) => !oversized.includes(row) && isDirectory(row.content));
  const toDelete = [...duplicates, ...oversized, ...boilerplate];
  const remaining = rows.length - toDelete.length + newChunks.size;

  console.log("Plan");
  console.log(`  1. Duplicados exactos a borrar:      ${duplicates.length}  (quedan ${unique.length} filas únicas)`);
  console.log(`  2. Filas enormes (> ${MAX_ROW_CHARS} caracteres): ${oversized.length}  → se dividen; ${newChunks.size} fragmento(s) nuevo(s), el resto ya existe`);
  for (const row of oversized) console.log(`       - ${row.content.length} caracteres: ${preview(row.content, 90)}…`);
  console.log(`  3. Filas que solo son encabezado/pie de página a borrar: ${boilerplate.length}`);
  for (const row of boilerplate) console.log(`       - ${preview(row.content)}…`);
  console.log(`  Directorio de veterinarios (MVRA): ${directory.length} filas únicas — no se tocan (paso 1.4)`);
  console.log(`\n  Total: ${rows.length} filas → ${remaining} filas (${toDelete.length} borradas, ${newChunks.size} insertadas)`);

  const planFile = backupFile.replace(/\.json$/, ".plan.json");
  fs.writeFileSync(
    planFile,
    JSON.stringify(
      {
        delete: toDelete.map((row) => ({
          id: row.id,
          reason: duplicates.includes(row) ? "duplicate" : oversized.includes(row) ? "oversized" : "boilerplate",
          chars: row.content.length,
          preview: preview(row.content),
        })),
        insert: [...newChunks].map((content) => ({ chars: content.length, preview: preview(content) })),
      },
      null,
      2,
    ),
  );
  console.log(`  Detalle fila por fila: ${path.relative(process.cwd(), planFile)}`);

  const sqlFile = backupFile.replace(/\.json$/, ".cleanup.sql");
  fs.writeFileSync(sqlFile, planToSql(toDelete.map((row) => row.id)));
  console.log(`  Mismo plan en SQL (para el SQL Editor de Supabase): ${path.relative(process.cwd(), sqlFile)}`);

  if (!apply) {
    console.log("\nSimulación: no se cambió nada. Para aplicar: npm run clean-docs -- --yes");
    return;
  }

  const admin = adminClient();
  if (!admin) {
    console.error(
      "\nNo se aplicó nada: la base no permite borrar con la llave anon (RLS)." +
        "\nOpción A: agrega SUPABASE_SERVICE_ROLE_KEY a .env y vuelve a correr con --yes." +
        `\nOpción B: pega ${path.relative(process.cwd(), sqlFile)} en Supabase → SQL Editor → Run.`,
    );
    process.exit(1);
  }

  // Insert first, delete second: if anything fails midway, nothing is lost.
  console.log("\nAplicando…");
  for (const content of newChunks) {
    const embedding = await generateEmbedding(content);
    const { error } = await supabase.from("documents").insert({ content, embedding });
    if (error) throw error;
  }
  let deleted = 0;
  const ids = toDelete.map((row) => row.id);
  for (let i = 0; i < ids.length; i += 100) {
    const { data, error } = await admin.from("documents").delete().in("id", ids.slice(i, i + 100)).select("id");
    if (error) throw error;
    deleted += data?.length ?? 0;
  }
  if (deleted !== ids.length) {
    throw new Error(`Se esperaban ${ids.length} filas borradas y se borraron ${deleted}. Revisa permisos (RLS).`);
  }
  console.log(`✅ Insertadas ${newChunks.size}, borradas ${deleted}. Para deshacer: npm run clean-docs -- --restore ${path.relative(process.cwd(), backupFile)}`);
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
